#!/bin/bash
# =============================================================================
#  /etc/keepalived/check_apiserver.sh
#  วางเหมือนกันทั้ง 3 master · chmod 700
# =============================================================================
#  keepalived เรียกสคริปต์นี้ทุก 3 วินาที
#    exit 0  = เครื่องนี้ยังทำหน้าที่ได้  → priority คงเดิม
#    exit 1  = เครื่องนี้มีปัญหา          → priority ลดลง → VIP ย้ายไปเครื่องอื่น
#
#  ตรวจ 3 ด่านตามลำดับ:
#    1. HAProxy บนเครื่องนี้ยังฟัง 8443 อยู่ไหม        — ตรวจเสมอ
#    2. มี kube-apiserver บนเครื่องนี้หรือยัง            — ถ้ายัง ผ่านเลย
#    3. ถ้าถือ VIP อยู่ — ต่อผ่าน VIP แล้วถึง apiserver จริงไหม
#
#  ด่าน 2 มีไว้กัน VIP กระพริบระหว่าง bootstrap — อ่านเหตุผลเต็มตรงตัวโค้ด
#  ห้ามเอาออกโดยไม่อ่านก่อน มันไม่ใช่โค้ดซ้ำซ้อน
# =============================================================================

VIP=192.168.50.100
VIP_PORT=8443

errorExit() {
    echo "check_apiserver: $*" >&2
    exit 1
}

# --- 1. HAProxy บนเครื่องนี้ตอบไหม -------------------------------------------
# ข้อนี้ตรวจเสมอ ทุกช่วงเวลา — HAProxy ตายเมื่อไหร่ต้องย้าย VIP ทันที
if ! ss -lnt | grep -q ":${VIP_PORT} "; then
    errorExit "HAProxy ไม่ได้ฟังที่พอร์ต ${VIP_PORT}"
fi

# --- 2. ยังไม่มี kube-apiserver บนเครื่องนี้ = ยังอยู่ช่วง bootstrap ----------
# ผ่านไปก่อน อย่าเพิ่งไปตรวจข้อ 3
#
# ⚠️ ถ้าไม่มี guard นี้ ระหว่าง bootstrap (ก่อน kubeadm init) จะเกิด VIP กระพริบ:
#     เครื่องที่ถือ VIP ยิง /healthz ไม่ผ่าน เพราะ HAProxy ยังไม่มี backend เป็น ๆ
#     → track_script หัก priority 20 → เครื่องอื่นแย่ง VIP ไป
#     → เครื่องใหม่ถือ VIP ก็ตกด้วยเหตุผลเดียวกัน → วนไม่จบทุก ~6-12 วินาที
#     เจอจริงมาแล้ว: master02 สลับ MASTER/BACKUP 3 ครั้งใน 15 วินาที
#     และมีจังหวะที่ VIP ขึ้นสองเครื่องพร้อมกันตอนสับเปลี่ยน
#
# เหตุผลที่ข้ามได้อย่างปลอดภัย: HAProxy กระจายไป apiserver ทั้ง 3 ตัว
# ถ้า apiserver ในเครื่องนี้ตายแต่เครื่องอื่นยังอยู่ VIP ก็ยังทำงานได้ปกติ
# ไม่มีเหตุให้ต้องย้าย — และถ้าตายหมดทั้ง 3 ตัว การย้าย VIP ก็ไม่ช่วยอะไร
# มีแต่ทำให้กระพริบเปล่า ๆ
if ! ss -lnt | grep -q ':6443 '; then
    exit 0
fi

# --- 3. ถือ VIP อยู่ + มี apiserver แล้ว → ต้องยิงผ่าน VIP ถึงจริง ------------
# ข้อนี้จับเคสที่ apiserver เป็นปกติ แต่เส้นทาง VIP → HAProxy บนเครื่องนี้พัง
if ip -4 addr show | grep -q "inet ${VIP}/"; then
    curl --silent --max-time 2 --insecure \
         "https://${VIP}:${VIP_PORT}/healthz" -o /dev/null \
      || errorExit "ถือ VIP อยู่ แต่ยิง https://${VIP}:${VIP_PORT}/healthz ไม่ผ่าน"
fi

exit 0
